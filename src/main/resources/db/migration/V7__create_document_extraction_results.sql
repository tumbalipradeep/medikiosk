-- M1.2: Persist clinical document text-extraction results.
--
-- One extraction row per clinical document (1:1). Page-level text is stored
-- separately so ordering is preserved and large bodies of text do not bloat
-- the document metadata row. The original uploaded binary stays on the local
-- filesystem and is never copied into the database.

CREATE TABLE IF NOT EXISTS clinical_document_extractions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinical_document_id BIGINT         NOT NULL,
    status               VARCHAR(20)    NOT NULL,
    extracted_text       TEXT,
    page_count           INTEGER        NOT NULL DEFAULT 0,
    error_category       VARCHAR(30),
    error_message        VARCHAR(255),
    extracted_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_extraction_clinical_document UNIQUE (clinical_document_id),
    CONSTRAINT fk_extraction_clinical_document
        FOREIGN KEY (clinical_document_id) REFERENCES clinical_documents (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_extraction_clinical_document
    ON clinical_document_extractions (clinical_document_id);

CREATE TABLE IF NOT EXISTS clinical_document_page_texts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extraction_id BIGINT      NOT NULL,
    page_number   INTEGER     NOT NULL,
    page_text     TEXT        NOT NULL,
    CONSTRAINT fk_page_text_extraction
        FOREIGN KEY (extraction_id) REFERENCES clinical_document_extractions (id) ON DELETE CASCADE,
    CONSTRAINT uq_extraction_page UNIQUE (extraction_id, page_number)
);

CREATE INDEX IF NOT EXISTS idx_page_text_extraction_order
    ON clinical_document_page_texts (extraction_id, page_number);