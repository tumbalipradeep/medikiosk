-- MediKiosk RW2: data-driven medication interaction screening.
--
-- The engine that consumes these tables is deliberately thin and generic:
-- profiles map recognized drug names to a canonical identity + therapeutic
-- class, and interaction rules declare pairs by canonical drug name or class
-- key. Rules are stored as data so a clinician can extend the screening set
-- without a code change. This is a screening aid, never a prescription or a
-- diagnosis; the physician remains the sole author of clinical decisions.
--
-- case_medications records only the physician overlay for a case: medicines
-- the physician added to the case screen, and name-based suppression
-- tombstones that remove a sourced medicine (patient history or document
-- findings) from the computed list. Sourced medicines themselves are always
-- re-derived from the clinical history and document findings, never copied.

CREATE TABLE IF NOT EXISTS medication_profiles (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name VARCHAR(80) NOT NULL,
    class_key      VARCHAR(40) NOT NULL,
    aliases        VARCHAR(500),
    description    VARCHAR(500),
    CONSTRAINT uq_medication_profile_canonical UNIQUE (canonical_name)
);

CREATE TABLE IF NOT EXISTS medication_interaction_rules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_a     VARCHAR(80) NOT NULL,
    group_b     VARCHAR(80) NOT NULL,
    severity    VARCHAR(32) NOT NULL,
    title       VARCHAR(200) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    guidance    VARCHAR(1000) NOT NULL,
    CONSTRAINT ck_interaction_severity CHECK (severity IN (
        'CONTRAINDICATED', 'MAJOR', 'MODERATE', 'MINOR'))
);

CREATE TABLE IF NOT EXISTS case_medications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id       VARCHAR(64) NOT NULL
        REFERENCES completed_cases (case_id) ON DELETE CASCADE,
    med_name      VARCHAR(150) NOT NULL,
    dose          VARCHAR(80),
    frequency     VARCHAR(80),
    source        VARCHAR(32) NOT NULL,
    added_by      BIGINT REFERENCES users (id),
    added_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    suppressed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_case_medication_name UNIQUE (case_id, med_name),
    CONSTRAINT ck_case_medication_source CHECK (source IN (
        'PATIENT_HISTORY', 'DOCUMENT_FINDING', 'PHYSICIAN_ENTERED'))
);

